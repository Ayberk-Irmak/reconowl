"""Native check: WAF / security-proxy detection.

Runs ``wafw00f`` when available, otherwise fingerprints the response to an
obviously-malicious request natively. Knowing a WAF sits in front of the target
explains blocks and tells the operator to slow down (``--stealth``).
"""

from __future__ import annotations

import re

from ..models import Finding, ScanResult, Severity
from ..utils.tools import find_tool, run

_SOURCE = "native:waf"

# Response header/body signatures -> WAF/CDN name.
_SIGNATURES = {
    "cloudflare": ("cf-ray", "cloudflare", "__cfduid", "cf-cache-status"),
    "Akamai": ("akamai", "akamaighost", "x-akamai"),
    "Imperva Incapsula": ("incap_ses", "x-iinfo", "visid_incap"),
    "Sucuri": ("x-sucuri", "sucuri/cloudproxy"),
    "AWS WAF / CloudFront": ("awselb", "x-amz-cf-id", "x-amzn-requestid"),
    "F5 BIG-IP ASM": ("bigipserver", "ts01", "x-waf-event"),
    "Barracuda": ("barra_counter_session", "barracuda"),
    "ModSecurity": ("mod_security", "modsecurity", "not acceptable"),
    "Fortinet FortiWeb": ("fortiwafsid", "fortigate"),
    "Wordfence": ("wordfence", "this response was generated by wordfence"),
}

# A benign vs. an obviously-malicious probe: a WAF usually blocks the latter.
_ATTACK = "?reconowlwaf=<script>alert(1)</script>&x=' OR '1'='1"
_BLOCK_STATUSES = (403, 406, 429, 501, 999)


def _wafw00f(url: str) -> str:
    if find_tool("wafw00f") is None:
        return ""
    code, out, _err = run("wafw00f", [url], timeout=60.0)
    m = re.search(r"is behind\s+(.+?)\s+WAF", out)
    if m:
        return m.group(1).strip()
    if "is behind" in out:
        return re.sub(r"\s+", " ", out.split("is behind", 1)[1]).strip()[:60]
    return ""


def _fingerprint(headers: dict, body: str) -> str:
    hay = " ".join(f"{k}:{v}" for k, v in (headers or {}).items()).lower() + " " + (body or "").lower()
    for name, sigs in _SIGNATURES.items():
        if any(s in hay for s in sigs):
            return name
    return ""


def detect(base_url: str, config, client) -> str:
    """Return a detected WAF name, or empty string."""
    if config.use_external:
        name = _wafw00f(base_url)
        if name:
            return name
    benign = client.get(base_url)
    attack = client.get(base_url.rstrip("/") + "/" + _ATTACK)
    name = _fingerprint(benign.headers, "") or _fingerprint(attack.headers, attack.text)
    if name:
        return name
    # Behavioural: malicious request blocked while the benign one was fine.
    if benign.ok and benign.status == 200 and attack.ok and attack.status in _BLOCK_STATUSES:
        return "generic (behavioural)"
    return ""


def check(result: ScanResult, config, client, ui) -> list[Finding]:
    base = result.target.base_url
    if not base:
        return []
    name = detect(base, config, client)
    if not name:
        return []
    result.waf = name
    ui.warn(f"WAF/security proxy detected: {name}. Consider --stealth to avoid blocks.")
    return [
        Finding(
            title=f"WAF / security proxy detected: {name}",
            severity=Severity.INFO,
            target=result.target.host,
            category="waf-detected",
            location=base,
            description=f"Traffic appears to pass through {name}. This can block or "
            "rate-limit scanning and may hide some findings.",
            remediation="Not a vulnerability by itself; note it for scan tuning and "
            "consider allowlisting the tester during an engagement.",
            evidence=name,
            source=_SOURCE,
        )
    ]
